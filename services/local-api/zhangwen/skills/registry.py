def _smart_skill(
    skill_id: str,
    name: str,
    description: str,
    input_schema: JsonSchemaObject,
    output_schema: JsonSchemaObject,
    required_tools: list[str],
    risk_level: SkillRiskLevel,
    confirmation_policy: SkillConfirmationPolicy,
    artifact_types: list[str],
    permissions: list[SkillPermission],
    now: str,
) -> SkillDefinition:
    return SkillDefinition(
        id=skill_id,
        name=name,
        description=description,
        origin=SkillOrigin.BUILT_IN,
        enabled=True,
        ownerExpert="smart_engineer",
        inputSchema=input_schema,
        outputSchema=output_schema,
        requiredTools=required_tools,
        riskLevel=risk_level,
        confirmationPolicy=confirmation_policy,
        artifactTypes=artifact_types,
        permissions=permissions,
        createdAt=now,
        updatedAt=now,
    )


def _expert_skill(
    skill_id: str,
    name: str,
    description: str,
    owner_expert: str,
    input_schema: JsonSchemaObject,
    output_schema: JsonSchemaObject,
    artifact_types: list[str],
    now: str,
    *,
    risk_level: SkillRiskLevel = SkillRiskLevel.LOW,
    confirmation_policy: SkillConfirmationPolicy = SkillConfirmationPolicy.NEVER,
    required_tools: list[str] | None = None,
    permissions: list[SkillPermission] | None = None,
) -> SkillDefinition:
    return SkillDefinition(
        id=skill_id,
        name=name,
        description=description,
        origin=SkillOrigin.BUILT_IN,
        enabled=True,
        ownerExpert=owner_expert,
        inputSchema=input_schema,
        outputSchema=output_schema,
        riskLevel=risk_level,
        confirmationPolicy=confirmation_policy,
        requiredTools=required_tools or [],
        artifactTypes=artifact_types,
        permissions=permissions
        or [SkillPermission.READ_PROJECT, SkillPermission.WRITE_ARTIFACT],
        createdAt=now,
        updatedAt=now,
    )


def _fixed_time() -> str:
    return datetime(2026, 7, 8, tzinfo=UTC).isoformat()
