test('first AI send saves the draft once, preserves newer edits and retries failures', async ({ page }) => {
  let configured = true;
  await page.route('**/api/session', async route => {
    const response = await route.fetch();
    await route.fulfill({ json: { ...await response.json(), aiConfigured: configured } });
  });
  let releaseCreate!: () => void;
  const createGate = new Promise<void>(resolve => { releaseCreate = resolve; });
  let creates = 0;
  let savedId = '';
  await page.route('**/api/projects', async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return; }
    creates++;
    const response = await route.fetch(); savedId = (await response.json()).id;
    await createGate; await route.fulfill({ response });
  });
  const attempts: { message: string; code: string }[] = [];
  await page.route('**/api/projects/*/chat', async route => {
    const body = route.request().postDataJSON(); attempts.push(body);
    if (attempts.length === 1) { await route.fulfill({ status: 502, json: { detail: '模拟网络失败，请重试。' } }); return; }
    await route.fulfill({ json: { messages: [
      { id: 'fake-user', role: 'user', status: 'COMPLETED', content: body.message },
      { id: 'fake-assistant', role: 'assistant', status: 'COMPLETED', content: '模拟建议\n```python\nprint("suggested")\n```' },
    ] } });
  });
  await page.goto('/');
  const editor = page.getByRole('textbox', { name: 'MicroPython 代码编辑器' });
  const input = page.getByLabel('发送给掌问 AI');
  await editor.fill('print("first snapshot")\n');
  await input.fill('帮我检查');
  await expect(page.getByRole('button', { name: '发送', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await expect(page.getByLabel('掌问对话记录')).toContainText('正在发送');
  await expect(page.getByRole('button', { name: '发送', exact: true })).toBeDisabled();
  await editor.fill('print("edited during preparation")\n');
  await input.fill('新的输入不要覆盖');
  releaseCreate();
  await expect(page.locator('.chat-error')).toContainText('模拟网络失败');
  await expect(input).toHaveValue('新的输入不要覆盖');
  await expect(editor).toContainText('edited during preparation');
  const saved = await (await page.request.get('/api/projects/' + savedId)).json();
  expect(saved.code).toBe('print("first snapshot")\n');
  expect(creates).toBe(1);
  await input.press('Control+Enter');
  await expect(page.getByLabel('掌问对话记录')).toContainText('模拟建议');
  await expect(input).toHaveValue('');
  expect(attempts).toHaveLength(2);
  expect(attempts[1].code).toBe('print("edited during preparation")\n');
  expect(creates).toBe(1);
  await expect(editor).toContainText('edited during preparation');
  await expect(page.getByRole('button', { name: '查看代码', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '运行', exact: true })).toBeDisabled();
  configured = false;
  await input.fill('未配置时保留的问题');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'API 设置', exact: true })).toBeVisible();
  await expect(input).toHaveValue('未配置时保留的问题');
  expect(creates).toBe(1); expect(attempts).toHaveLength(2);
  await page.keyboard.press('Escape');
});

